"""Generate the extra e2e question clips with Piper. SYNTHETIC SPEECH (TTS), like evals/audio.

Runs inside the voice-app image, which has Piper and the voices:
  docker compose run --rm --no-deps -v "$PWD/e2e:/app/e2e" voice-app sh -c "PYTHONPATH=/app python e2e/scripts/make_clips.py"
Writes e2e/audio/*.wav and e2e/audio/clips.json (text, language, sha256). Commit both.
"""
from __future__ import annotations

import hashlib
import json
import os
import wave


from voice.tts import QUESTION_VOICES, PiperTTS

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "audio")

# Questions that no fleet tool can answer: the agent should say so, in the asker's language.
CLIPS = [
    {"id": "en_oos_weather", "lang": "en", "text": "What will the weather be like in Mumbai tomorrow?"},
    {"id": "hi_oos_cricket", "lang": "hi", "text": "कल क्रिकेट मैच का स्कोर क्या था?"},
]


def main():
    os.makedirs(OUT, exist_ok=True)
    manifest = {"note": "SYNTHETIC SPEECH generated by Piper TTS (e2e/scripts/make_clips.py)", "clips": []}
    tts = PiperTTS(QUESTION_VOICES)  # question voices differ from the reply voices, as in evals/make_audio.py
    for c in CLIPS:
        pcm, sr, _ = tts.synthesize(c["text"], c["lang"])  # 16-bit mono PCM bytes
        path = os.path.join(OUT, c["id"] + ".wav")
        with wave.open(path, "wb") as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr); w.writeframes(pcm)
        sha = hashlib.sha256(open(path, "rb").read()).hexdigest()
        manifest["clips"].append({**c, "file": f"e2e/audio/{c['id']}.wav", "sha256": sha, "synthetic_speech": True})
        print("wrote", path, sr, "Hz")
    with open(os.path.join(OUT, "clips.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
