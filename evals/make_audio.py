"""Generate the eval audio with Piper. ALL OF IT IS SYNTHETIC SPEECH (TTS), not human recordings.

  python -m evals.make_audio            # questions.jsonl + dev_questions.jsonl -> evals/audio/*.wav
Question voices differ from the reply voices (en: amy, hi: rohan, mr: google speaker 4), see voice/tts.py.
Noisy variants: the clean clip + pink noise + quiet babble (other questions) + 50 Hz hum, mixed at 10 dB SNR.
A manifest with sha256 per file is written to evals/audio/manifest.json.
"""
from __future__ import annotations

import hashlib
import json
import os
import wave

import numpy as np

from voice.tts import QUESTION_VOICES, PiperTTS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(path):
    return [json.loads(l) for l in open(os.path.join(ROOT, path), encoding="utf-8") if l.strip()]


def write_wav(path, x: np.ndarray, sr: int):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    pcm = (np.clip(x, -1, 1) * 32767).astype(np.int16)
    with wave.open(path, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr); w.writeframes(pcm.tobytes())


def pink(n, rng):
    white = rng.standard_normal(n)
    f = np.fft.rfft(white)
    f /= np.sqrt(np.maximum(np.arange(len(f)), 1))
    p = np.fft.irfft(f, n)
    return p / (np.abs(p).max() + 1e-9)


def mix_noise(clean: np.ndarray, sr: int, babble_src: list[np.ndarray], snr_db: float, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    n = len(clean)
    babble = np.zeros(n)
    for b in babble_src:
        off = rng.integers(0, max(1, n // 3))
        seg = b[: n - off]
        babble[off:off + len(seg)] += seg
    t = np.arange(n) / sr
    hum = 0.3 * np.sin(2 * np.pi * 50 * t)
    noise = 0.6 * pink(n, rng) + 0.4 * (babble / (np.abs(babble).max() + 1e-9)) + hum
    p_s = np.mean(clean ** 2)
    p_n = np.mean(noise ** 2)
    noise *= np.sqrt(p_s / (p_n * 10 ** (snr_db / 10)))
    out = clean + noise
    return out / max(1.0, np.abs(out).max() / 0.98)


def main():
    tts = PiperTTS(voices=QUESTION_VOICES)
    rows = load("evals/questions.jsonl") + load("evals/dev_questions.jsonl")
    clean: dict[str, tuple[np.ndarray, int]] = {}
    manifest = {}
    pad = 0.3
    for r in rows:
        if r.get("noise"):
            continue
        pcm, sr, _ = tts.synthesize(r["text"], r["lang"])
        x = np.frombuffer(pcm, dtype=np.int16).astype(np.float32) / 32768
        x = np.concatenate([np.zeros(int(pad * sr)), x, np.zeros(int(pad * sr))])
        clean[r["id"]] = (x, sr)
        write_wav(os.path.join(ROOT, r["audio"]), x, sr)
    for i, r in enumerate(x for x in rows if x.get("noise")):
        base = r["noise"]["base"]
        x, sr = clean[base]
        others = [clean[k][0] for k in clean if k != base and not k.startswith("dev")][i * 2:i * 2 + 2]
        y = mix_noise(x, sr, [o * 0.5 for o in others], r["noise"]["snr_db"], seed=100 + i)
        write_wav(os.path.join(ROOT, r["audio"]), y, sr)
    for r in rows:
        p = os.path.join(ROOT, r["audio"])
        manifest[r["audio"]] = hashlib.sha256(open(p, "rb").read()).hexdigest()
    json.dump({"note": "SYNTHETIC SPEECH generated by Piper TTS (evals/make_audio.py)", "files": manifest},
              open(os.path.join(ROOT, "evals/audio/manifest.json"), "w"), indent=1)
    print(f"wrote {len(manifest)} files to evals/audio/")


if __name__ == "__main__":
    main()
