"""Eval round 2: language-ID confusion matrices (en/hi/mr) from runs that are already logged. No new audio.

  python -m evals.lang_confusion

Sources (clean clips only, SYNTHETIC speech):
  evals/results/voice_claude_cli.jsonl   the main voice run (30 clean clips)
  evals/results/voice_rules.jsonl        the Docker default run (same clips, same STT; a consistency check)
  evals/results/noise_sweep/rows.jsonl   if present: the same matrix per noise condition
Two decisions are shown for each clip:
  whisper argmax   argmax of Whisper's language probabilities restricted to en/hi/mr (`lang_probs`), i.e.
                   what a plain "pick the most likely of the three" policy would say
  final (app)      `detected_lang`, the app's policy: EN_MIN threshold, decode hi/mr with the Marathi token,
                   then the hi-vs-mr word check in agent/lang.py; this is the language the reply is spoken in
"""
from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "evals", "results")
L = ["en", "hi", "mr"]


def argmax_lang(probs: dict) -> str:
    return max(L, key=lambda k: probs.get(k, 0.0))


def matrix(rows, pred) -> dict:
    m = {t: {p: 0 for p in L} for t in L}
    for r in rows:
        m[r["lang"]][pred(r)] += 1
    return m


def md(m, title) -> str:
    n = sum(sum(v.values()) for v in m.values())
    acc = sum(m[k][k] for k in L) / n if n else 0
    out = [f"**{title}**: accuracy {acc:.1%} ({sum(m[k][k] for k in L)}/{n})", "",
           "| true \\ predicted | en | hi | mr | recall |", "|---|---|---|---|---|"]
    for t in L:
        tot = sum(m[t].values())
        out.append(f"| {t} | " + " | ".join(str(m[t][p]) for p in L) + f" | {m[t][t] / tot:.0%} |" if tot else f"| {t} | 0 | 0 | 0 | – |")
    prec = []
    for p in L:
        col = sum(m[t][p] for t in L)
        prec.append(f"{m[p][p] / col:.0%}" if col else "–")
    out.append("| precision | " + " | ".join(prec) + " | |")
    return "\n".join(out)


def load(path):
    if not os.path.exists(path):
        return []
    return [json.loads(l) for l in open(path, encoding="utf-8") if l.strip()]


def main():
    parts = ["# Language-ID confusion (en/hi/mr), SYNTHETIC speech, clean clips", "",
             "Generated by `python -m evals.lang_confusion` from already-logged runs (no new STT).", ""]
    summary = {}
    for tag in ("voice_claude_cli", "voice_rules"):
        rows = [r for r in load(os.path.join(RES, f"{tag}.jsonl")) if not r.get("noisy")]
        if not rows:
            continue
        a = matrix(rows, lambda r: argmax_lang(r["lang_probs"]))
        f = matrix(rows, lambda r: r["detected_lang"])
        summary[tag] = {"whisper_argmax": a, "final": f, "n": len(rows)}
        parts += [f"## `{tag}.jsonl` ({len(rows)} clean clips)", "", md(a, "Whisper argmax over en/hi/mr"), "",
                  md(f, "Final language used by the app"), ""]
    sweep = load(os.path.join(RES, "noise_sweep", "rows.jsonl"))
    if sweep:
        parts += ["## Noise sweep (final language used by the app)", ""]
        conds = []
        for r in sweep:
            c = (r["noise"], r["snr_db"])
            if c not in conds:
                conds.append(c)
        for c in conds:
            g = [r for r in sweep if (r["noise"], r["snr_db"]) == c]
            f = matrix(g, lambda r: r["detected_lang"])
            summary[f"noise_sweep:{c[0]}:{c[1]}"] = {"final": f, "n": len(g)}
            parts += [md(f, f"{c[0]} {c[1]}{'' if c[1] == 'clean' else ' dB'}"), ""]
    text = "\n".join(parts)
    open(os.path.join(RES, "lang_confusion.md"), "w", encoding="utf-8").write(text + "\n")
    json.dump(summary, open(os.path.join(RES, "lang_confusion.json"), "w"), indent=1)
    print(text)


if __name__ == "__main__":
    main()
